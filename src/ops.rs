//! Operators

use crate::{
    CFnArg, CFnReturn, CType, Decode, Encode,
    stored::{EmptyStore, Store},
};

#[doc(hidden)]
pub struct PlainCall;
#[doc(hidden)]
pub struct BorrowedCall;

#[doc(hidden)]
pub trait CallEncode<C, M>: Sized {
    type Owner: Default;
    type Store: Store + Default;
    fn encode(self, store: &mut Self::Store, owner: &mut Self::Owner) -> C;
}
impl<T: Encode> CallEncode<T::CType, PlainCall> for T {
    type Owner = ();
    type Store = T::Store;
    fn encode(self, store: &mut Self::Store, _: &mut Self::Owner) -> T::CType {
        crate::soft_encode(self, store)
    }
}

impl<T: crate::borrow::BorrowedEncode> CallEncode<crate::borrow::CBorrowed<T>, BorrowedCall> for T {
    type Owner = T::Owner;
    type Store = T::Store;
    fn encode(
        self,
        store: &mut Self::Store,
        owner: &mut Self::Owner,
    ) -> crate::borrow::CBorrowed<T> {
        crate::borrow::CBorrowed(crate::borrow::BorrowedEncode::soft_encode(
            self, store, owner,
        ))
    }
}

#[doc(hidden)]
pub trait CallDecode<'d, C, M>: Sized {
    /// # Safety
    /// The input must satisfy the source type's decoding contract.
    unsafe fn decode(source: C) -> Option<Self>;
}
impl<'d, T: Decode<'d, Store: EmptyStore> + 'd> CallDecode<'d, T::CType, PlainCall> for T {
    unsafe fn decode(source: T::CType) -> Option<Self> {
        unsafe { crate::decode(source) }
    }
}

impl<'d, T: crate::borrow::BorrowedDecode<'d, Store: EmptyStore> + 'd>
    CallDecode<'d, crate::borrow::CBorrowed<T>, BorrowedCall> for T
{
    unsafe fn decode(source: crate::borrow::CBorrowed<T>) -> Option<Self> {
        unsafe { crate::borrow::decode(source) }
    }
}

macro_rules! define_fn_trait {
    ($name:ident, $arity:tt; $( $arg_ty:ident : $carg:ident : $arg:ident : $c_ty:ident ),* $(,)?) => {
        #[doc = concat!("The _C fn_ call operator of arity ", stringify!($arity), " that accepts Rust values.")]
        pub trait $name: Copy where Option<Self>: CType { $(

            #[doc = concat!("The ABI type of argument `", stringify!($arg), "`.")]
            type $carg: CFnArg;)*

            /// The ABI return type.
            type Output: CFnReturn;

            /// Calls the function with Rust arguments.
            ///
            /// Encodes arguments, calls the function, synchronizes conversion stores, and
            /// decodes the result. `CBorrowed` selects borrowed conversion; other carriers use ordinary conversion;
            /// borrowed argument owners remain alive until result decoding finishes.
            ///
            /// # Safety
            ///
            /// The caller must uphold the safety requirements of calling `self` and of
            /// decoding its return value according to the ABI ownership contract.
            /// Returned references must remain valid after temporary argument stores and
            /// owners are released; they must not borrow from that temporary storage.
            ///
            /// For companion functions generated by [`crate::raw!`], this returned-reference
            /// requirement is satisfied by the generated conversions and lifetime checks,
            /// provided the wrapped Rust function's own safety requirements are upheld.
            #[allow(clippy::too_many_arguments)]
            unsafe fn call<'d, $( $arg_ty, $carg, )* B, ReturnMode>(self $(, $arg: $arg_ty)*) -> Option<B>
            where $(
                $arg_ty: CallEncode<Self::$carg, $carg>, )*
                B: CallDecode<'d, Self::Output, ReturnMode> + 'd,
            {
                $(#[allow(non_snake_case)] let mut $carg = <$arg_ty as CallEncode<Self::$carg, $carg>>::Owner::default();)*
                $(#[allow(non_snake_case)] let mut $arg_ty = <$arg_ty as CallEncode<Self::$carg, $carg>>::Store::default();)*
                let result = unsafe { self.call_raw($(<$arg_ty as CallEncode<Self::$carg, $carg>>::encode($arg, &mut $arg_ty, &mut $carg)),*) };
                #[allow(unused_mut)]
                let mut sync_ok = true;
                $(sync_ok &= Store::sync($arg_ty).is_some();)*
                unsafe { B::decode(result) }.filter(|_| sync_ok)
            }

            /// # Safety
            /// The arguments and return value must obey this function's ABI contract.
            #[doc(hidden)]
            #[allow(clippy::too_many_arguments)]
            unsafe fn call_raw(self, $($arg: Self::$carg),*) -> Self::Output;
        }

        impl_fn_pointer_for_all_abis!($name; $( $arg_ty : $carg : $arg : $c_ty ),*);
    };
}

macro_rules! impl_fn_pointer {
    ($trait:ident; $abi:literal; $( $arg_ty:ident : $carg:ident : $arg:ident : $c_ty:ident ),* $(,)?) => {
        impl<$( $c_ty: CFnArg, )* U: CFnReturn> $trait for unsafe extern $abi fn($( $c_ty ),*) -> U
        where Option<Self>: CType
        { $(
            type $carg = $c_ty; )*
            type Output = U;

            #[allow(clippy::too_many_arguments)]
            unsafe fn call_raw(self, $($arg: Self::$carg),*) -> Self::Output {
                unsafe { self($($arg),*) }
            }

        }
    };
}

macro_rules! impl_fn_pointer_for_all_abis {
    ($trait:ident; $( $arg_ty:ident : $carg:ident : $arg:ident : $c_ty:ident ),* $(,)?) => {
        impl_fn_pointer!($trait; "C"; $( $arg_ty : $carg : $arg : $c_ty ),*);
        impl_fn_pointer!($trait; "C-unwind"; $( $arg_ty : $carg : $arg : $c_ty ),*);
        impl_fn_pointer!($trait; "system"; $( $arg_ty : $carg : $arg : $c_ty ),*);
        impl_fn_pointer!($trait; "system-unwind"; $( $arg_ty : $carg : $arg : $c_ty ),*);
        #[cfg(target_arch = "x86")]
        impl_fn_pointer!($trait; "cdecl"; $( $arg_ty : $carg : $arg : $c_ty ),*);
        #[cfg(target_arch = "x86")]
        impl_fn_pointer!($trait; "cdecl-unwind"; $( $arg_ty : $carg : $arg : $c_ty ),*);
        #[cfg(target_arch = "x86")]
        impl_fn_pointer!($trait; "stdcall"; $( $arg_ty : $carg : $arg : $c_ty ),*);
        #[cfg(target_arch = "x86")]
        impl_fn_pointer!($trait; "stdcall-unwind"; $( $arg_ty : $carg : $arg : $c_ty ),*);
        #[cfg(target_arch = "x86")]
        impl_fn_pointer!($trait; "fastcall"; $( $arg_ty : $carg : $arg : $c_ty ),*);
        #[cfg(target_arch = "x86")]
        impl_fn_pointer!($trait; "fastcall-unwind"; $( $arg_ty : $carg : $arg : $c_ty ),*);
        #[cfg(target_arch = "x86")]
        impl_fn_pointer!($trait; "thiscall"; $( $arg_ty : $carg : $arg : $c_ty ),*);
        #[cfg(target_arch = "x86")]
        impl_fn_pointer!($trait; "thiscall-unwind"; $( $arg_ty : $carg : $arg : $c_ty ),*);
        #[cfg(target_arch = "x86_64")]
        impl_fn_pointer!($trait; "sysv64"; $( $arg_ty : $carg : $arg : $c_ty ),*);
        #[cfg(target_arch = "x86_64")]
        impl_fn_pointer!($trait; "sysv64-unwind"; $( $arg_ty : $carg : $arg : $c_ty ),*);
        #[cfg(target_arch = "x86_64")]
        impl_fn_pointer!($trait; "win64"; $( $arg_ty : $carg : $arg : $c_ty ),*);
        #[cfg(target_arch = "x86_64")]
        impl_fn_pointer!($trait; "win64-unwind"; $( $arg_ty : $carg : $arg : $c_ty ),*);
        #[cfg(target_arch = "arm")]
        impl_fn_pointer!($trait; "aapcs"; $( $arg_ty : $carg : $arg : $c_ty ),*);
        #[cfg(target_arch = "arm")]
        impl_fn_pointer!($trait; "aapcs-unwind"; $( $arg_ty : $carg : $arg : $c_ty ),*);
        #[cfg(any(target_arch = "x86", target_arch = "x86_64", target_arch = "arm", target_arch = "aarch64"))]
        impl_fn_pointer!($trait; "efiapi"; $( $arg_ty : $carg : $arg : $c_ty ),*);
    };
}

